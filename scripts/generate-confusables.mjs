import { writeFile } from 'node:fs/promises';

const unicodeVersion = '17.0.0';
const url = 'https://www.unicode.org/Public/security/latest/confusables.txt';
const response = await fetch(url);
if (!response.ok) throw new Error(`Confusable-Daten konnten nicht geladen werden: ${response.status} ${url}`);
const sourceText = await response.text();
if (!sourceText.includes(`# Version: ${unicodeVersion}`)) throw new Error(`Erwartet wurde confusables.txt für Unicode ${unicodeVersion}.`);

const mappings = new Map();
let maxSourceLength = 1;
for (const line of sourceText.split(/\r?\n/)) {
  const value = line.split('#', 1)[0].trim();
  if (!value) continue;
  const [source, target] = value.split(';').map((field) => field.trim());
  if (!source || !target) continue;
  const sourceText = String.fromCodePoint(...source.split(/\s+/).map((point) => Number.parseInt(point, 16))).normalize('NFD').toLocaleLowerCase('und');
  const targetText = String.fromCodePoint(...target.split(/\s+/).map((point) => Number.parseInt(point, 16))).normalize('NFD').toLocaleLowerCase('und');
  mappings.set(sourceText, targetText);
  maxSourceLength = Math.max(maxSourceLength, [...sourceText].length);
}

const table = [...mappings.entries()].sort(([left], [right]) => left.localeCompare(right));
const output = `// Generated by scripts/generate-confusables.mjs from Unicode ${unicodeVersion}. Do not edit manually.\nexport const confusableDataVersion = '${unicodeVersion}';\nexport const maxConfusableSourceLength = ${maxSourceLength};\nexport const confusableMappings = new Map<string, string>(${JSON.stringify(table, null, 2)});\n`;
await writeFile(new URL('../src/lib/cleaner/generated-confusables.ts', import.meta.url), output);
