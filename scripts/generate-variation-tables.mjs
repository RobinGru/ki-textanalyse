import { writeFile } from 'node:fs/promises';

const unicodeVersion = '17.0.0';
const ivdVersion = '2026-08-03';
const sources = [
  ['standardized', `https://www.unicode.org/Public/${unicodeVersion}/ucd/StandardizedVariants.txt`],
  ['emoji', `https://www.unicode.org/Public/${unicodeVersion}/ucd/emoji/emoji-variation-sequences.txt`]
];
const ivdSource = `https://www.unicode.org/ivd/data/${ivdVersion}/IVD_Sequences.txt`;

const entries = new Map();
for (const [kind, url] of sources) {
  const response = await fetch(url);
  if (!response.ok) throw new Error(`Unicode-Daten konnten nicht geladen werden: ${response.status} ${url}`);
  for (const line of (await response.text()).split(/\r?\n/)) {
    const value = line.split('#', 1)[0].trim();
    if (!value) continue;
    const [sequence] = value.split(';', 1);
    const codepoints = sequence.trim().split(/\s+/);
    if (codepoints.length !== 2) continue;
    entries.set(codepoints.join('-'), kind);
  }
}

const table = [...entries.entries()].sort(([left], [right]) => left.localeCompare(right));
const ivdResponse = await fetch(ivdSource);
if (!ivdResponse.ok) throw new Error(`IVD-Daten konnten nicht geladen werden: ${ivdResponse.status} ${ivdSource}`);
const ivdEntries = new Set();
for (const line of (await ivdResponse.text()).split(/\r?\n/)) {
  const value = line.split('#', 1)[0].trim();
  if (!value) continue;
  const [sequence] = value.split(';', 1);
  const codepoints = sequence.trim().split(/\s+/);
  if (codepoints.length === 2) ivdEntries.add(codepoints.join('-'));
}
const ideographicTable = [...ivdEntries].sort((left, right) => left.localeCompare(right));
const output = `// Generated by scripts/generate-variation-tables.mjs from Unicode ${unicodeVersion} and IVD ${ivdVersion}. Do not edit manually.\nexport const unicodeVariationDataVersion = '${unicodeVersion}';\nexport const ideographicVariationDataVersion = '${ivdVersion}';\nexport const registeredVariationSequences = new Map<string, 'emoji' | 'standardized'>([\n${table.map(([key, kind]) => `  ['${key}', '${kind}'],`).join('\n')}\n]);\nexport const registeredIdeographicVariationSequences = new Set<string>([\n${ideographicTable.map((key) => `  '${key}',`).join('\n')}\n]);\n`;
await writeFile(new URL('../src/lib/cleaner/generated-variation-sequences.ts', import.meta.url), output);
